function pickLang() {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  if (LANGS.includes(fromUrl)) return fromUrl;
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch {}
  return DEFAULT_LANG;
}

let lang = pickLang();
const langListeners = [];

function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

// Static text in the page: data-i18n sets the text, data-i18n-<attr> sets that attribute.
function applyI18n(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("*")) {
    for (const a of el.getAttributeNames()) {
      if (a.startsWith("data-i18n-")) el.setAttribute(a.slice("data-i18n-".length), t(el.getAttribute(a)));
    }
  }
  const picker = document.getElementById("lang-select");
  if (picker) picker.value = lang;
}

function setLang(l) {
  if (!LANGS.includes(l) || l === lang) return;
  lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch {}
  const url = new URL(location.href);
  if (url.searchParams.has("lang")) {
    url.searchParams.set("lang", l);
    history.replaceState(null, "", url);
  }
  applyI18n();
  for (const fn of langListeners) fn(l);
}

applyI18n();
document.getElementById("lang-select")?.addEventListener("change", (e) => setLang(e.target.value));
